</p>

<p>
    I understand that Redmond Medical &amp; Mental Health is a non-emergent clinic. If I am feeling
    worse or my symptoms are not improving, I understand it is my responsibility to either seek
    emergent/urgent medical care or contact the clinic. If I have an emergency (including suicidal
    ideation), I agree to call 911 or go to the nearest hospital. If I have urgent medical needs
    that occur after-hours, I understand that I will need to go to an urgent care center as there
    may not be a Redmond Medical and Mental Health provider available to speak with me 24 hours a
