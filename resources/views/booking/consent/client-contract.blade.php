<h2>Client Contract</h2>

<p>
    As either the client or the legally authorized representative of the client, on behalf of the
    client receiving care with Redmond Medical &amp; Mental Health, I make the following consents,
    understandings, and agreements on my own behalf and on behalf of the client, in consideration of
    health care services to be provided to the client: Welcome and thank you for choosing Redmond
    Medical &amp; Mental Health. We are dedicated to providing quality medical and psychiatric care
    to our clients. Please review the information below regarding your care and let us know if you
    have any questions or concerns regarding the following information.
</p>

<h3>HIPPA</h3>

<p>
    I understand that all information disclosed within sessions or during visits is kept
    confidential and is not revealed to anyone without my permission. I give my permission for
    Redmond Medical &amp; Mental Health to discuss my care with my healthcare team so that
    collaborative care plans can be made in my best interest. I further understand that there are
    specific and limited exceptions to this confidentiality, which include the following:
</p>

<ul>
    <li>
        When there is risk of imminent danger to myself or to another person, the clinician is
        ethically bound to take necessary steps to prevent such danger.
    </li>
    <li>
        When there is suspicion that a child, elder, or vulnerable adult is being neglected,
        sexually or physically abused, or is at risk of such abuse, the clinician is legally
        required to take steps to protect the child or adult, and to inform the proper authorities.
    </li>
    <li>
        When a valid court order is issued for medical records, Redmond Medical &amp; Mental Health
        practitioners are bound by law to comply with such requests.
    </li>
</ul>

<h3>Consent to Treat</h3>

<p>
    I hereby give consent to Redmond Medical &amp; Mental Health practitioners, Tiffany Redmond,
    PA-C, and any contractors and employees to provide healthcare services to the client and to
    administer provider orders for the benefit of the client for this visit and any subsequent
    visits. I understand this consent may be revoked in writing at any time. I understand there is a
    risk of substantial and serious harm of any particular involved in such health care services and
    I accept such risk in the hope of obtaining beneficial results from such services. No promises
    of any particular outcome or successful result have been made. I understand that providers
    (Physician Assistants, Nurse Practitioners and therapists) are separately responsible to explain
    what they do and in some cases, such as medical procedures, to obtain separate consent for some
    of the services they perform.
</p>

<p>
    I understand that some health care providers furnishing service to the client, including interns
    and professionals in training/students, may be independent contractors and not employees of
    Redmond Medical &amp; Mental Health which are subject to provisions of the Utah Governmental
    Immunity act, UCA 63-30-1, et seq., U.C.A. 1953 as amended, which controls all procedures and
    provisions with respect to any claim of liability or malpractice involving such individuals.
</p>

<p>
    I understand that Tiffany Redmond is a licensed Physician Assistant and able to order medical
    tests and medications, as well as diagnose, treat, and perform specific medical procedures
    within the state of Utah.
</p>

<p>
    I understand it is my responsibility to be accountable for my own health. If I do not hear from
    someone to help schedule additional testing or schedule with a referred provider/specialist, I
    understand it is my responsibility to notify my practitioner/clinic so that I can get assistance
    in doing so. I understand it is my responsibility to notify my practitioner about any side
    effects, worsening conditions, or lack of improvement I may be experiencing. If my symptoms
    suddenly worsen, I agree to either contact the clinic and notify my practitioner or seek
    urgent/emergent care if appropriate.
</p>

<p>
    If patient is a minor, a legal guardian must also sign the form. If parents are divorced,
    informed consent must be signed by whoever is declared, in the divorce decree, as custody
    holder(s). For example, if there is joint custody, both parents MUST sign the informed consent.
    A copy of the divorce decree is needed by the 2nd session/visit to continue therapy if both
    parents do not sign the informed consent. By signing the Informed Consent, I voluntarily agree
    to receive health assessment, care, treatment, or services and authorize Tiffany Redmond and any
    employed practitioners to provide such care, treatment, or services as deemed necessary and
    advisable. My signature indicates that I understand and agree that I will participate in the
    planning of my care, treatment, or services and that I may stop such care, treatment, or
    services at any time. By signing the Informed Consent, I acknowledge that I have both read and
    understand all the terms and information contained herein.
</p>

<h3>Consent to Share Health Information</h3>

<p>
    I authorize Tiffany Redmond of Redmond Medical &amp; Mental Health to release my personal
    healthcare information (such as testing results) to the individual(s) who I have listed as my
    Emergency Contact and understand this release is valid unless I request to revoke the authorized
    person, in writing.
</p>

<h3>Privacy Practice and Release of Information</h3>

<p>
    We are required by law to make and keep records of our client's medical treatment. Our facility
    safeguards those records and uses and discloses such records and the information they contain
    only in accordance with State and Federal privacy laws. Such uses and disclosures are described
    in detail in the Notice of Privacy Practices, which may be amended from time to time. I
    understand that I, the client, may ask to see a copy of the current notice at any time. Our
    responsibility by law is to maintain the privacy of your protected and personal health
    information, provide an available written notice of our legal duties and privacy policies,
    notify you if there is a discovery that there has been any breach of your protected health
    information, accommodate reasonable requests for communication regarding your confidential
    communication, and process your requests for medical records within a timely manner (typically
    within 10 days). You have the right to request to restrict disclosure of your information for
    certain items you pay for out of pocket, you have the right to request confidential
    communication and the right to inspect your protect health information. Your request of any
    personal protected health information may be sent directly to another person if your request is
    provided clearly in writing, is signed by you and clearly identifies the designated person and
    where to send the copy. You may request information on how your information has been disclosed
    for purposes other than for treatment, payment, and healthcare operations. you have the right to
    request amendments to your medical records as well as request a copy of our privacy policy. You
    have the right to discuss any concerns with us or with the State/Health and Human Services.
    Disclosures of health information may be used and disclosed only for the following reasons:
</p>

<ul>
    <li>
        If needed to diagnose and treat your condition. This includes sharing information with other
        providers who are treating you, providers who you are being referred to and collaborating
        practitioners. This also includes the reporting of specific infectious diseases.
    </li>
    <li>Payment (billing your insurance, responsible parties/billing and coding services)</li>
    <li>
        Providing information to Utah Medicaid and Children's Health Insurance Program eligibility
        database
    </li>
    <li>Evaluation regarding quality of treatment and services provided</li>
    <li>
        Appointment reminders (we may leave appointment reminders on voicemail, with family/friends,
        via email or text messaging unless otherwise requested in writing.
    </li>
    <li>Treatment alternatives (we may inform you of alternative treatment options),</li>
    <li>If required by law (release of information if requested by law enforcement),</li>
    <li>Suspected abuse or neglect</li>
    <li>
        With your authorization (with your signed consent we may disclose your health information to
        a specific entity for a specific purpose).
    </li>
</ul>

<p>
    <strong>Visits/Gathering Information:</strong> During initial and subsequent visits, my provider
    will gather information about me and my history. I understand that it is my responsibility to
    help my provider to gather accurate information. This includes providing up-to-date medication
    lists with doses, bringing copies of prior treatment records (if available or if they can be
    reasonably obtained), and being as honest and forthcoming as possible. My provider will
    recommend closely spaced follow-up visits after medication changes (such as starting new
    medications, tapering off medications, dose changes, or wellness plans) and during times of
    medical need. I understand that these visits are for my safety and benefit and that it is my
    responsibility to comply.
</p>

<p>
    I understand it is my responsibility to schedule follow up appointments as advised. The
    receptionist is only available to reschedule appointments during business hours and I will make
    an effort to call during these times, whenever possible. I agree to pay a $40 fee for missing
    scheduled appointments or for failing to cancel an appointment greater than 24 hours in advance
    (a voicemail message is acceptable if the receptionist is unavailable as long as it is at least
    24-hour notice). I understand that if I am more than 15 minutes late for a scheduled
    appointment, I may be asked to reschedule my appointment and I will be charged a $15 service
    fee. If I have not been seen in 1 year or more, I understand that I will no longer be considered
    an active patient. To resume care through my provider, I would then need to be scheduled as a
    new patient, depending on availability and make sure any unpaid balance on my account is paid in
    full. I agree to inform Redmond Medical &amp; Mental Health if my contact information changes
    during the course of treatment.
</p>

<h3>Payment and Financial Policy</h3>

<p>
    I understand that my co-payments/co-insurance is due at the time of service. As a courtesy to
    you, Redmond Medical &amp; Mental Health will submit bills directly to your insurance company as
    per the information you provide us. Your cooperation in giving complete information including
    insurance company name, address, telephone number, policy number and group number will assist in
    getting your insurance claim paid quickly. A copy of your insurance card is also requested.
</p>

<p>
    <strong>Payment of your Bill:</strong> Regardless of the type of insurance coverage, you are
    ultimately responsible for payment of your medical bills. Cash payments will be collected before
    each appointment. If your insurance is accepted, then reasonable efforts will be implemented to
    obtain payment from your insurance company. If they reject the claims or do not pay within 60
    days, payment will be your responsibility. Payment of known deductibles, co-pays and non-covered
    services is expected at the time of service. After reasonable collection efforts have been made
    any account balance not satisfied will be turned over to a third-party collection agency. You
    are responsible for any finance, collection or attorney fees associated with collection of the
    unpaid balance.
</p>

<p>
    I have read the FINANCIAL POLICY STATEMENT and understand that any charges incurred are my
    responsibility and I have given correct billing information. I understand that I will be
    responsible for any finance, collection or attorney fees associated with collection of these
    charges.
</p>

<p>
    Should your account be turned over for collection, the undersigned agrees to pay all costs to
    collect the debt, including, but not limited to, interest in the amount of 18% per annum,
    attorney's fees, court costs, and collection fees in the amount of 40%. The obligation to pay
    the collection fees shall be imposed at the time of assignment of the debt to a third-party debt
    collection agency.
</p>

<p>
    <strong>Assignment of Benefits:</strong> Any and all benefits from insurance companies and other
    third-party payors that are payable to the client or on behalf of the client for healthcare
    services and related payments for services rendered or provided to the client are hereby
    transferred and assigned to Redmond Medical &amp; Mental Health for the exclusive purpose of
    paying for charges associated with the health care services provided to the client. I understand
    and intend that all insurance companies and other third-party payers will pay benefits directly
    to the provider in payment of the incurred charges and the charges of any other healthcare
    providers authorized to bill in connection with healthcare services provided to the patient.
</p>

<p>
    <strong>Medication History Authority:</strong> I grant authority to Redmond Medical &amp; Mental
